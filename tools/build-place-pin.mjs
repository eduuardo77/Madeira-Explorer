/**
 * The map's place pin, rendered to the PNG the app ships (N12, 2026-10-25).
 *
 *     node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON tools/build-place-pin.mjs
 *     → app/src/map/placePinPng.ts (generated), tools/out/place-pin.png (to look at)
 *
 * The drawing is `app/src/map/placePin.ts`. The PNG travels to the native map
 * as base64 in a TypeScript constant rather than as an image asset: in a
 * release build a bundled image is an Android resource, not a file the map's
 * native side can open by path. Rerun after any change to the drawing;
 * `placePin.test.ts` fails until then.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { PIN_PNG_SCALE, PIN_WIDTH_DP, placePinFingerprint, placePinSvg } from '../app/src/map/placePin.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const svg = placePinSvg();
const png = new Resvg(svg, { fitTo: { mode: 'width', value: PIN_WIDTH_DP * PIN_PNG_SCALE } }).render().asPng();

const out = path.join(here, '..', 'app', 'src', 'map', 'placePinPng.ts');
writeFileSync(
  out,
  [
    '// Generated by tools/build-place-pin.mjs from placePin.ts. Do not edit.',
    `export const PLACE_PIN_FINGERPRINT = '${placePinFingerprint(svg)}';`,
    `export const PLACE_PIN_PNG_BASE64 =\n  '${png.toString('base64')}';`,
    '',
  ].join('\n')
);
mkdirSync(path.join(here, 'out'), { recursive: true });
writeFileSync(path.join(here, 'out', 'place-pin.png'), png);
console.log(`${out} (${png.length} bytes)`);
